/** 中文名 → slug 反向索引（检索用；一个中文名可命中多个 slug 的别名场景手动控制） */
export const ZH_TO_SLUGS: Record<string, string[]> = (() => {
  const map: Record<string, string[]> = {}
  for (const [slug, zh] of Object.entries(MOD_ZH)) {
    const key = zh.toLowerCase()
    if (!map[key]) map[key] = []
    map[key].push(slug)
  }
  return map
})()

